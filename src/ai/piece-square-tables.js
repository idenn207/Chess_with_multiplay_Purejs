// Piece-Square Tables for Chess Position Evaluation
// 각 기물의 위치별 가치 테이블 (백 기준, 흑은 상하 반전)

class PieceSquareTables {
  constructor() {
    // 폰 위치 가치 테이블
    // 전진할수록 가치 증가, 중앙 선호
    this.pawnTable = [
      [0, 0, 0, 0, 0, 0, 0, 0],
      [50, 50, 50, 50, 50, 50, 50, 50],
      [10, 10, 20, 30, 30, 20, 10, 10],
      [5, 5, 10, 25, 25, 10, 5, 5],
      [0, 0, 0, 20, 20, 0, 0, 0],
      [5, -5, -10, 0, 0, -10, -5, 5],
      [5, 10, 10, -20, -20, 10, 10, 5],
      [0, 0, 0, 0, 0, 0, 0, 0],
    ];

    // 나이트 위치 가치 테이블
    // 중앙 위치 선호, 가장자리 페널티
    this.knightTable = [
      [-50, -40, -30, -30, -30, -30, -40, -50],
      [-40, -20, 0, 0, 0, 0, -20, -40],
      [-30, 0, 10, 15, 15, 10, 0, -30],
      [-30, 5, 15, 20, 20, 15, 5, -30],
      [-30, 0, 15, 20, 20, 15, 0, -30],
      [-30, 5, 10, 15, 15, 10, 5, -30],
      [-40, -20, 0, 5, 5, 0, -20, -40],
      [-50, -40, -30, -30, -30, -30, -40, -50],
    ];

    // 비숍 위치 가치 테이블
    // 중앙 및 긴 대각선 선호
    this.bishopTable = [
      [-20, -10, -10, -10, -10, -10, -10, -20],
      [-10, 0, 0, 0, 0, 0, 0, -10],
      [-10, 0, 5, 10, 10, 5, 0, -10],
      [-10, 5, 5, 10, 10, 5, 5, -10],
      [-10, 0, 10, 10, 10, 10, 0, -10],
      [-10, 10, 10, 10, 10, 10, 10, -10],
      [-10, 5, 0, 0, 0, 0, 5, -10],
      [-20, -10, -10, -10, -10, -10, -10, -20],
    ];

    // 룩 위치 가치 테이블
    // 7번째 랭크 선호 (상대 2번째 줄)
    this.rookTable = [
      [0, 0, 0, 0, 0, 0, 0, 0],
      [5, 10, 10, 10, 10, 10, 10, 5],
      [-5, 0, 0, 0, 0, 0, 0, -5],
      [-5, 0, 0, 0, 0, 0, 0, -5],
      [-5, 0, 0, 0, 0, 0, 0, -5],
      [-5, 0, 0, 0, 0, 0, 0, -5],
      [-5, 0, 0, 0, 0, 0, 0, -5],
      [0, 0, 0, 5, 5, 0, 0, 0],
    ];

    // 퀸 위치 가치 테이블
    // 중앙 위치 선호
    this.queenTable = [
      [-20, -10, -10, -5, -5, -10, -10, -20],
      [-10, 0, 0, 0, 0, 0, 0, -10],
      [-10, 0, 5, 5, 5, 5, 0, -10],
      [-5, 0, 5, 5, 5, 5, 0, -5],
      [0, 0, 5, 5, 5, 5, 0, -5],
      [-10, 5, 5, 5, 5, 5, 0, -10],
      [-10, 0, 5, 0, 0, 0, 0, -10],
      [-20, -10, -10, -5, -5, -10, -10, -20],
    ];

    // 킹 중반전 위치 가치 테이블
    // 캐슬링 위치 선호 (모서리)
    this.kingMiddleGameTable = [
      [-30, -40, -40, -50, -50, -40, -40, -30],
      [-30, -40, -40, -50, -50, -40, -40, -30],
      [-30, -40, -40, -50, -50, -40, -40, -30],
      [-30, -40, -40, -50, -50, -40, -40, -30],
      [-20, -30, -30, -40, -40, -30, -30, -20],
      [-10, -20, -20, -20, -20, -20, -20, -10],
      [20, 20, 0, 0, 0, 0, 20, 20],
      [20, 30, 10, 0, 0, 10, 30, 20],
    ];

    // 킹 엔드게임 위치 가치 테이블
    // 중앙 위치 선호
    this.kingEndGameTable = [
      [-50, -40, -30, -20, -20, -30, -40, -50],
      [-30, -20, -10, 0, 0, -10, -20, -30],
      [-30, -10, 20, 30, 30, 20, -10, -30],
      [-30, -10, 30, 40, 40, 30, -10, -30],
      [-30, -10, 30, 40, 40, 30, -10, -30],
      [-30, -10, 20, 30, 30, 20, -10, -30],
      [-30, -30, 0, 0, 0, 0, -30, -30],
      [-50, -30, -30, -30, -30, -30, -30, -50],
    ];
  }

  /**
   * 특정 기물의 위치 가치를 반환
   * @param {string} pieceType - 기물 종류 ('p', 'n', 'b', 'r', 'q', 'k')
   * @param {number} row - 행 (0-7)
   * @param {number} col - 열 (0-7)
   * @param {boolean} isWhite - 백 기물 여부
   * @param {boolean} isEndGame - 엔드게임 여부 (킹 테이블 선택용)
   * @returns {number} 위치 가치
   */
  getValue(pieceType, row, col, isWhite, isEndGame = false) {
    let table;

    switch (pieceType) {
      case 'p':
        table = this.pawnTable;
        break;
      case 'n':
        table = this.knightTable;
        break;
      case 'b':
        table = this.bishopTable;
        break;
      case 'r':
        table = this.rookTable;
        break;
      case 'q':
        table = this.queenTable;
        break;
      case 'k':
        table = isEndGame ? this.kingEndGameTable : this.kingMiddleGameTable;
        break;
      default:
        return 0;
    }

    // 흑 기물은 테이블을 상하 반전
    const lookupRow = isWhite ? row : 7 - row;
    return table[lookupRow][col];
  }
}
